"""Quicksort and Mergesort (divide and conquer) with step counting and logging."""

LOG_FILE = "mergesort_log.txt"
REPORT_FILE = "pivot_experiment.txt"


# ---------------------------------------------------------------- Quicksort
def quicksort(arr, pivot_choice="last", counter=None):
    """Sort a copy of arr. pivot_choice: 'last' (default) or 'first'.

    counter is a dict; counter['steps'] counts element comparisons against the pivot.
    """
    a = list(arr)
    if counter is None:
        counter = {"steps": 0}
    _quicksort(a, 0, len(a) - 1, pivot_choice, counter)
    return a


def _quicksort(a, lo, hi, pivot_choice, counter):
    if lo >= hi:
        return
    p = _partition(a, lo, hi, pivot_choice, counter)
    _quicksort(a, lo, p - 1, pivot_choice, counter)
    _quicksort(a, p + 1, hi, pivot_choice, counter)


def _partition(a, lo, hi, pivot_choice, counter):
    # Move the chosen pivot to the end, then partition with the last element as pivot.
    if pivot_choice == "first":
        a[lo], a[hi] = a[hi], a[lo]
    pivot = a[hi]
    i = lo - 1
    for j in range(lo, hi):
        counter["steps"] += 1
        if a[j] <= pivot:
            i += 1
            a[i], a[j] = a[j], a[i]
    a[i + 1], a[hi] = a[hi], a[i + 1]
    return i + 1


# ---------------------------------------------------------------- Mergesort
def mergesort(arr, log=None, depth=0):
    """Return a sorted copy. Splits down to single elements, then merges.

    log is an optional list; intermediate stages are appended as strings.
    """
    indent = "  " * depth
    if len(arr) <= 1:
        if log is not None:
            log.append(f"{indent}BASE   {list(arr)}  (single-element unit)")
        return list(arr)

    mid = len(arr) // 2
    left_part, right_part = arr[:mid], arr[mid:]
    if log is not None:
        log.append(f"{indent}SPLIT  {list(arr)} -> {left_part} | {right_part}")

    left = mergesort(left_part, log, depth + 1)
    right = mergesort(right_part, log, depth + 1)

    merged = []
    i = j = 0
    while i < len(left) and j < len(right):
        if left[i] <= right[j]:
            merged.append(left[i])
            i += 1
        else:
            merged.append(right[j])
            j += 1
    merged.extend(left[i:])
    merged.extend(right[j:])
    if log is not None:
        log.append(f"{indent}MERGE  {left} + {right} -> {merged}")
    return merged


# --------------------------------------------------------------- Experiment
def pivot_experiment(datasets):
    rows = []
    for name, data in datasets:
        c_last, c_first = {"steps": 0}, {"steps": 0}
        r_last = quicksort(data, "last", c_last)
        r_first = quicksort(data, "first", c_first)
        rows.append((name, data, c_last["steps"], c_first["steps"], r_last, r_first))
    return rows


def write_report(rows, path=REPORT_FILE):
    lines = [
        "PIVOT EXPERIMENT: Quicksort, last element vs first element as pivot",
        "=" * 66,
        "Metric: number of comparisons of an element against the pivot",
        "(one 'step' = one comparison inside the partition loop).",
        "",
    ]
    for name, data, s_last, s_first, r_last, r_first in rows:
        lines += [
            f"Dataset: {name}  {data}",
            f"  Last-element pivot : {s_last} steps -> {r_last}",
            f"  First-element pivot: {s_first} steps -> {r_first}",
            "",
        ]
    lines += [
        "Findings",
        "--------",
        "1. On the required sample [5, 3, 8, 1, 2] the last-element pivot took",
        f"   {rows[0][2]} steps and the first-element pivot took {rows[0][3]} steps;",
        "   both sort correctly to [1, 2, 3, 5, 8]. The small difference comes from",
        "   how evenly each pivot splits this particular array.",
        "2. Pivot choice only matters when the data has structure. On already",
        "   sorted input, both a first-element and a last-element pivot always pick",
        "   the minimum or maximum, so each partition removes only one element and",
        "   the cost grows to n(n-1)/2 comparisons (O(n^2)).",
        "3. On reverse-sorted input the same degeneration happens, again for both",
        "   pivot choices. Neither choice is better in general; a random or",
        "   median-of-three pivot avoids these cases.",
    ]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    data = [5, 3, 8, 1, 2]
    expected = [1, 2, 3, 5, 8]

    print(f"Input array     : {data}")
    q = quicksort(data, "last")
    print(f"Quicksort result: {q}   {'OK' if q == expected else 'FAIL'}")

    log = [f"Mergesort intermediate stages for {data}", "-" * 60]
    m = mergesort(data, log)
    log.append("-" * 60)
    log.append(f"Final sorted result: {m}")
    with open(LOG_FILE, "w") as f:
        f.write("\n".join(log) + "\n")
    print(f"Mergesort result: {m}   {'OK' if m == expected else 'FAIL'}")

    rows = pivot_experiment([
        ("sample", data),
        ("already sorted", [1, 2, 3, 5, 8]),
        ("reverse sorted", [8, 5, 3, 2, 1]),
    ])
    write_report(rows)
    print(f"Wrote {LOG_FILE} and {REPORT_FILE}")


if __name__ == "__main__":
    main()