"""Linear search, binary search, and a modulo-based hash table (chaining or probing)."""
import csv


# ------------------------------------------------------------- Linear search
def linear_search(arr, target):
    """Return (index or -1, comparisons). Works on unsorted data."""
    comparisons = 0
    for i, value in enumerate(arr):
        comparisons += 1
        if value == target:
            return i, comparisons
    return -1, comparisons


# ------------------------------------------------------------- Binary search
def binary_search(arr, target, verbose=False):
    """Return (index or -1, comparisons). arr must be sorted.

    One comparison = one probe of arr[mid] against the target.
    """
    low, high = 0, len(arr) - 1
    comparisons = 0
    while low <= high:
        mid = (low + high) // 2
        comparisons += 1
        if verbose:
            print(f"  Comparison {comparisons}: low={low}, high={high}, "
                  f"mid=(({low} + {high}) // 2)={mid}, arr[{mid}]={arr[mid]}")
        if arr[mid] == target:
            return mid, comparisons
        if arr[mid] < target:
            low = mid + 1
        else:
            high = mid - 1
    return -1, comparisons


# ---------------------------------------------------------------- Hash table
class HashTable:
    """Fixed-size table with hash(key) = key % size.

    method='chaining': each slot holds a list of keys.
    method='probing' : linear probing, (index + 1) % size until a free slot.
    """

    def __init__(self, size=7, method="chaining"):
        self.size = size
        self.method = method
        self.slots = [[] for _ in range(size)] if method == "chaining" else [None] * size

    def hash(self, key):
        return key % self.size

    def insert(self, key):
        """Insert key; return (home_index, final_index, collided)."""
        home = self.hash(key)
        if self.method == "chaining":
            collided = len(self.slots[home]) > 0
            self.slots[home].append(key)
            return home, home, collided
        idx = home
        collided = self.slots[idx] is not None
        for _ in range(self.size):
            if self.slots[idx] is None:
                self.slots[idx] = key
                return home, idx, collided
            idx = (idx + 1) % self.size
        raise OverflowError("hash table is full")

    def search(self, key):
        """Return the slot index holding key, or -1."""
        idx = self.hash(key)
        if self.method == "chaining":
            return idx if key in self.slots[idx] else -1
        for _ in range(self.size):
            if self.slots[idx] is None:
                return -1
            if self.slots[idx] == key:
                return idx
            idx = (idx + 1) % self.size
        return -1

    def show(self):
        for i, s in enumerate(self.slots):
            if self.method == "chaining":
                chain = " -> ".join(str(k) for k in s) if s else "empty"
            else:
                chain = "empty" if s is None else str(s)
            print(f"  [{i}] {chain}")


# --------------------------------------------------------------------- Demos
def demo_binary():
    data = [1, 2, 3, 5, 8]
    print(f"Binary Search on sorted array {data}, target 5")
    idx, comps = binary_search(data, 5, verbose=True)
    print(f"  Found 5 at index {idx} with {comps} comparisons")
    print()
    idx, comps = binary_search(data, 7)
    print(f"Target 7 in sorted array {data}: "
          f"{'found at ' + str(idx) if idx >= 0 else 'NOT present'} ({comps} comparisons)")
    unsorted = [5, 3, 8, 1, 2]
    idx, comps = linear_search(unsorted, 7)
    print(f"Target 7 in unsorted array {unsorted} (linear): "
          f"{'found at ' + str(idx) if idx >= 0 else 'NOT present'} ({comps} comparisons)")
    idx, comps = linear_search(unsorted, 8)
    print(f"Target 8 in unsorted array {unsorted} (linear): found at index {idx} ({comps} comparisons)")


def demo_hash(path="hash_results.csv"):
    keys = [12, 25, 19]

    print("Hash function: h(key) = key % 7")
    for k in keys:
        print(f"  h({k}) = {k} % 7 = {k % 7}")
    print()

    print("Inserting 12, 25, 19 with CHAINING:")
    ht = HashTable(7, "chaining")
    rows = []
    for k in keys:
        home, final, collided = ht.insert(k)
        note = f"  <-- COLLISION at index {home}, chained after existing key" if collided else ""
        print(f"  insert {k}: index {home}{note}")
        rows.append([k, f"{k} % 7", home, "yes" if collided else "no"])
    print("Table after chaining:")
    ht.show()
    print()

    print("Inserting 12, 25, 19 with LINEAR PROBING:")
    hp = HashTable(7, "probing")
    probe_final = {}
    for k in keys:
        home, final, collided = hp.insert(k)
        probe_final[k] = final
        note = f"  <-- COLLISION at index {home}, probed to index {final}" if collided else ""
        print(f"  insert {k}: home index {home}{note}")
    print("Table after probing:")
    hp.show()

    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["key", "hash_function", "index", "collision", "final_slot_with_probing"])
        for (k, expr, idx, coll) in rows:
            w.writerow([k, expr, idx, coll, probe_final[k]])
    return ht


